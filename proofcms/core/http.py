DEFAULT_USER_AGENT = "ProofCMS/2.1 authorized-audit"
DEFAULT_ACCEPT = "text/html,application/xhtml+xml,application/xml;q=0.9,*/*;q=0.8"
DEFAULT_ACCEPT_LANGUAGE = "en-US,en;q=0.9,pt-BR;q=0.8"
MAX_RESPONSE_BYTES = 512 * 1024
_TLS_VERIFY = True
_thread_clients = threading.local()
_discovery_cache: dict[tuple[str, int, str | None, bool, bool, str], dict[str, Any]] = {}
_discovery_cache_enabled = False
_discovery_cache_lock = threading.Lock()
_rate_limit_rps: float | None = None
_rate_limit_next = 0.0
_rate_limit_lock = threading.Lock()


def configure_rate_limit(requests_per_second: float | None) -> None:
    """Set a process-wide request rate (0/None disables the limiter)."""
    global _rate_limit_rps, _rate_limit_next
    value: float | None = None
    if requests_per_second is not None:
        parsed = float(requests_per_second)
        if math.isnan(parsed) or math.isinf(parsed) or parsed < 0:
            raise ValueError("rate limit must be a finite non-negative number")
        value = parsed if parsed > 0 else None
    with _rate_limit_lock:
        _rate_limit_rps = value
        _rate_limit_next = 0.0


def _acquire_rate_limit() -> None:
    """Reserve the next request slot and sleep until it is due."""
    global _rate_limit_next
    with _rate_limit_lock:
        rps = _rate_limit_rps
        if not rps:
            return
        now = time.monotonic()
        wait = max(0.0, _rate_limit_next - now)
        _rate_limit_next = max(now, _rate_limit_next) + (1.0 / rps)
    if wait > 0:
        time.sleep(wait)


def begin_discovery_cache() -> None:
    """Enable a per-target cache for idempotent detector GETs."""
    global _discovery_cache_enabled
    with _discovery_cache_lock:
        _discovery_cache.clear()
        _discovery_cache_enabled = True


def end_discovery_cache() -> None:
    """Disable and clear the discovery cache before active probes run."""
    global _discovery_cache_enabled
    with _discovery_cache_lock:
        _discovery_cache.clear()
        _discovery_cache_enabled = False


def _close_thread_clients() -> None:
    clients = getattr(_thread_clients, "clients", None) or {}
    for client in clients.values():
        session = getattr(client, "session", None)
        if session is not None:
            session.close()
    _thread_clients.clients = {}


def configure_tls(verify: bool = True) -> None:
    """Set the process-wide TLS policy used by newly created clients."""
    global _TLS_VERIFY
    _TLS_VERIFY = verify
    _close_thread_clients()


def reset_transport_state() -> None:
    """Drop thread-local clients so cookies never cross target boundaries."""
    _close_thread_clients()
    end_discovery_cache()


def tls_verification_enabled() -> bool:
    """Return the process-wide TLS verification policy."""
    return _TLS_VERIFY


def detect_edge_interstitial(body: str, final_url: str = "", headers: Any = None) -> str | None:
    """Identify known bot/WAF challenge pages that commonly return HTTP 200."""
    haystack = f"{final_url}\n{body[:128 * 1024]}".lower()
    header_map: dict[str, str] = {}
    if headers is not None and hasattr(headers, "items"):
        for key, value in headers.items():
            header_map[str(key).lower()] = str(value).lower()

    if any(
        marker in haystack
        for marker in (
            "validate.perfdrive.com",
            "radware captcha page",
            "shieldsquare",
            "__uzma",
            "__uzmb",
        )
    ):
        return "radware-bot-manager"

    if (
        "challenge" in header_map.get("cf-mitigated", "")
        or "__cf_chl_opt" in haystack
        or "attention required! | cloudflare" in haystack
        or (
            "just a moment..." in haystack
            and ("cloudflare" in haystack or "cloudflare" in header_map.get("server", ""))
        )
        or (
            "cf-chl-" in haystack
            and ("cloudflare" in haystack or "cloudflare" in header_map.get("server", ""))
        )
    ):
        return "cloudflare"

    if (
        "sucuri website firewall - access denied" in haystack
        or ("sucuri website firewall" in haystack and "access denied" in haystack)
        or "x-sucuri-block" in header_map
    ):
        return "sucuri"

    if (
        "generated by wordfence" in haystack
        or "your access to this site has been limited" in haystack
    ):
        return "wordfence"

    if (
        "_incapsula_resource" in haystack
        or "incapsula incident id" in haystack
        or ("visid_incap_" in haystack and ("incapsula" in haystack or "access denied" in haystack))
        or (
            "x-iinfo" in header_map
            and ("incapsula" in haystack or "access denied" in haystack)
        )
    ):
        return "imperva-incapsula"

    if "mod_security" in haystack or "modsecurity" in haystack:
        return "modsecurity"

    if "imunify360" in haystack or ("imunify" in haystack and "blocked" in haystack):
        return "imunify360"

    return None


def _normalize_dynamic_html(body: str, url: str = "") -> str:
    """Remove common per-request values before comparing fake-200 pages.

    Soft-200 targets often echo the requested path (canonical links, form
    actions, breadcrumbs).  Normalizing the path to a placeholder lets the
    baseline canary and a probed route compare equal when the server renders
    the same page for both.
    """
    normalized = re.sub(r"\b[a-f0-9]{32}\b", "<joomla-token>", body, flags=re.IGNORECASE)
    normalized = re.sub(
        r"([?&](?:token|nonce|sid|session(?:id)?)=)[^&\"'<>\s]+",
        r"\1<dynamic>",
        normalized,
        flags=re.IGNORECASE,
    )
    if url:
        try:
            parsed = urllib.parse.urlsplit(url)
        except ValueError:
            parsed = None
        candidates: set[str] = set()
        for candidate in (url, url.rstrip("/")):
            if candidate and len(candidate) > 1:
                candidates.add(candidate)
        if parsed is not None:
            for candidate in (parsed.path, parsed.path.rstrip("/")):
                if candidate and len(candidate) > 1:
                    candidates.add(candidate)
        for candidate in sorted(candidates, key=len, reverse=True):
            normalized = normalized.replace(candidate, "<request-url>")
            for quoted in (
                urllib.parse.quote(candidate, safe=""),
                urllib.parse.quote(candidate, safe="/:?=&%"),
            ):
                if quoted and quoted != candidate:
                    normalized = normalized.replace(quoted, "<request-url>")
    normalized = re.sub(r"/_jvh_probe_[0-9a-f]+/?", "<probe-path>", normalized, flags=re.IGNORECASE)
    return re.sub(r"\s+", " ", normalized).strip()


def _html_title(body: str) -> str:
    match = re.search(r"<title\b[^>]*>(.*?)</title>", body, flags=re.IGNORECASE | re.DOTALL)
    if not match:
        return ""
    return re.sub(r"\s+", " ", match.group(1)).strip().lower()


def _decode_body(body_bytes: bytes, headers: Any) -> tuple[bytes, str, bool]:
    """Decode bounded content encoding and character encoding metadata."""
    encoding = str(headers.get("Content-Encoding", "")).lower()
    decoded_bytes = body_bytes
    encoding_truncated = False
    if encoding in {"gzip", "deflate"}:
        try:
            window = 16 + zlib.MAX_WBITS if encoding == "gzip" else zlib.MAX_WBITS
            decompressor = zlib.decompressobj(window)
            decoded_bytes = decompressor.decompress(body_bytes, MAX_RESPONSE_BYTES + 1)
            encoding_truncated = len(decoded_bytes) > MAX_RESPONSE_BYTES or bool(decompressor.unconsumed_tail)
            decoded_bytes = decoded_bytes[:MAX_RESPONSE_BYTES]
        except zlib.error:
            decoded_bytes = body_bytes
    charset = headers.get_content_charset() if hasattr(headers, "get_content_charset") else None
    if not charset:
        content_type = str(headers.get("Content-Type", "")) if hasattr(headers, "get") else ""
        match = re.search(r"charset=([A-Za-z0-9._-]+)", content_type, re.IGNORECASE)
        if match:
            charset = match.group(1)
    try:
        body = decoded_bytes.decode(charset or "utf-8", errors="replace")
    except LookupError:
        body = decoded_bytes.decode("utf-8", errors="replace")
    return decoded_bytes, body, encoding_truncated


def normalize_url(url: str, timeout: int = 0, proxy: str | None = None) -> str:
    """Validate and normalize an HTTP(S) target without performing network I/O."""
    del timeout, proxy  # retained for API compatibility
    value = url.strip()
    if not value:
        raise ValueError("target URL is empty")
    if "://" not in value:
        value = "https://" + value
    parsed = urllib.parse.urlsplit(value)
    scheme = parsed.scheme.lower()
    if scheme not in {"http", "https"}:
        raise ValueError(f"unsupported URL scheme: {parsed.scheme or '(missing)'}")
    if not parsed.hostname:
        raise ValueError("target URL must include a hostname")
    if parsed.query or parsed.fragment:
        raise ValueError("target URL must not include a query string or fragment")
    try:
        port = parsed.port
    except ValueError as exc:
        raise ValueError(f"invalid target port: {exc}") from exc
    host = parsed.hostname.lower()
    if ":" in host and not host.startswith("["):
        host = f"[{host}]"
    userinfo = ""
    if parsed.username is not None:
        userinfo = urllib.parse.quote(parsed.username, safe="")
        if parsed.password is not None:
            userinfo += ":" + urllib.parse.quote(parsed.password, safe="")
        userinfo += "@"
    netloc = f"{userinfo}{host}{f':{port}' if port is not None else ''}"
    path = re.sub(r"/{2,}", "/", parsed.path or "").rstrip("/")
    return urllib.parse.urlunsplit((scheme, netloc, path, "", ""))


_FILE_LIKE_PATH = re.compile(
    r"\.(?:aspx?|ashx|asmx|axd|svc|php\d?|phtml|jsp|jspx|do|action|cgi|pl|shtml|html?|xhtml)$",
    re.IGNORECASE,
)


def application_base_url(url: str) -> str:
    """Return the directory URL that should be used as a scan root.

    A target that names a document (``/portal/app.aspx``) must not become a
    directory (``/portal/app.aspx/``): appending ``/`` to a file makes a
    relative redirect such as ``Location: applogin.aspx`` resolve inside the
    file (``/portal/app.aspx/applogin.aspx``) and can close a 301 loop.
    Strip the document segment instead.
    """
    parts = urllib.parse.urlsplit(url.strip())
    if not parts.scheme or not parts.netloc:
        return url.rstrip("/")
    path = parts.path or ""
    if _FILE_LIKE_PATH.search(path):
        path = path.rsplit("/", 1)[0]
    path = path.rstrip("/")
    return urllib.parse.urlunsplit((parts.scheme, parts.netloc, path, "", ""))


def _multipart_param(value: str, parameter: str) -> str:
    """Format one Content-Disposition parameter without header injection."""
    text = str(value)
    if "\r" in text or "\n" in text:
        raise ValueError(f"invalid multipart {parameter}: CR/LF is not allowed")
    try:
        text.encode("latin-1")
    except UnicodeEncodeError:
        return f"{parameter}*=UTF-8''{urllib.parse.quote(text, safe='')}"
    escaped = text.replace("\\", "\\\\").replace('"', '\\"')
    return f'{parameter}="{escaped}"'


def build_multipart(fields: dict, files: dict) -> tuple[str, bytes]:
    """
    Constructs a multipart/form-data payload with boundary.
    fields: dict of {name: value}
    files: dict of {field_name: (filename, data, content_type)}
    Returns: (content_type_header_val, body_bytes)
    """
    payload = b"".join(
        [str(value).encode("utf-8") for value in fields.values()]
        + [
            data if isinstance(data, bytes) else str(data).encode("utf-8")
            for _, data, _ in files.values()
        ]
    )
    for _ in range(8):
        boundary = secrets.token_bytes(16).hex()
        if boundary.encode("ascii") not in payload:
            break
    else:
        raise ValueError("could not generate a collision-free multipart boundary")
    body = b""
    for name, value in fields.items():
        body += f"--{boundary}\r\n".encode("latin-1")
        body += f"Content-Disposition: form-data; {_multipart_param(name, 'name')}\r\n\r\n".encode("latin-1")
        body += str(value).encode("utf-8") + b"\r\n"
    for field_name, (filename, data, content_type) in files.items():
        body += f"--{boundary}\r\n".encode("latin-1")
        disposition = (
            f"Content-Disposition: form-data; {_multipart_param(field_name, 'name')}; "
            f"{_multipart_param(filename, 'filename')}"
        )
        body += f"{disposition}\r\n".encode("latin-1")
        body += f"Content-Type: {content_type}\r\n\r\n".encode("latin-1")
        body += data if isinstance(data, bytes) else data.encode("utf-8")
        body += b"\r\n"
    body += f"--{boundary}--\r\n".encode("latin-1")
    return f"multipart/form-data; boundary={boundary}", body


def form_encode(fields: dict) -> bytes:
    """Encode form fields into URL-encoded bytes."""
    return urllib.parse.urlencode(fields).encode("utf-8")


def _build_response_dict(
    status: int,
    body: str,
    requested_url: str,
    final_url: str,
    headers: Any = None,
    raw_bytes: bytes = b"",
    *,
    error: dict[str, str] | None = None,
    truncated: bool = False,
) -> dict[str, Any]:
    headers_dict: dict[str, Any] = dict(headers) if headers else {}
    header_items = list(headers.items()) if hasattr(headers, "items") else list(headers_dict.items())
    headers_multi: dict[str, list[str]] = {}
    for key, value in header_items:
        headers_multi.setdefault(str(key).lower(), []).append(str(value))
    content_type = next(
        (str(value) for key, value in headers_dict.items() if key.lower() == "content-type"),
        "",
    )
    body_hash = hashlib.sha256(raw_bytes if raw_bytes else body.encode("utf-8", errors="replace")).hexdigest()
    normalized_body = _normalize_dynamic_html(body, final_url)
    return {
        "status": status,
        "body": body,
        "url": final_url,
        "requested_url": requested_url,
        "final_url": final_url,
        "redirected": (requested_url.rstrip("/") != final_url.rstrip("/")),
        "headers": headers_dict,
        "headers_multi": headers_multi,
        "content_type": content_type,
        "body_hash": body_hash,
        "normalized_body_hash": hashlib.sha256(normalized_body.encode("utf-8")).hexdigest(),
        "body_len": len(body),
        "title": _html_title(body),
        "edge_interstitial": detect_edge_interstitial(body, final_url, headers),
        "error": error,
        "truncated": truncated,
        "captured_bytes": len(raw_bytes),
    }


def is_transport_error(response: dict[str, Any] | None) -> bool:
    """Return True when no HTTP response was received."""
    if not response:
        return False
    try:
        status = int(response.get("status", 0) or 0)
    except (TypeError, ValueError):
        status = 0
    return status <= 0 and bool(response.get("error"))


def transport_error_detail(response: dict[str, Any] | None) -> str:
    """Render a concise transport failure without turning it into a security result."""
    error = (response or {}).get("error") or {}
    if isinstance(error, dict):
        return f"{error.get('type') or 'TransportError'}: {error.get('message') or 'no response received'}"
    return str(error) or "no response received"


class _RequestsResponse:
    """Small urllib-like wrapper around a streaming requests response."""

    def __init__(self, response: requests.Response):
        self._response = response
        self.status = response.status_code
        self.url = response.url
        raw_headers = getattr(response.raw, "headers", None)
        self.headers = raw_headers if raw_headers is not None else response.headers

    def read(self, amt: int | None = None) -> bytes:
        if amt is None:
            data = self._response.raw.read()
        else:
            data = self._response.raw.read(amt, decode_content=False)
        return data or b""

    def close(self) -> None:
        self._response.close()

    def __enter__(self) -> Self:
        return self

    def __exit__(self, *args: object) -> None:
        self.close()


def _ip_is_private(address: ipaddress.IPv4Address | ipaddress.IPv6Address) -> bool:
    return bool(
        address.is_private
        or address.is_loopback
        or address.is_link_local
        or address.is_reserved
        or address.is_multicast
        or address.is_unspecified
    )


def _host_is_private(url: str) -> bool:
    """Return True when a URL host is loopback, private or otherwise local."""
    host = urllib.parse.urlsplit(url).hostname
    if not host:
        return False
    lowered = host.lower()
    if lowered in {"localhost", "localhost.localdomain"} or lowered.endswith(".local"):
        return True
    try:
        return _ip_is_private(ipaddress.ip_address(host))
    except ValueError:
        pass
    try:
        infos = socket.getaddrinfo(host, None, proto=socket.IPPROTO_TCP)
    except OSError:
        return False
    for info in infos:
        try:
            if _ip_is_private(ipaddress.ip_address(info[4][0])):
                return True
        except ValueError:
            continue
    return False


def _redirect_allowed(current_url: str, target_url: str) -> bool:
    """Allow HTTP(S) redirects that do not pivot a public scan into a local host."""
    target = urllib.parse.urlsplit(target_url)
    if target.scheme.lower() not in {"http", "https"}:
        return False
    return not (_host_is_private(target_url) and not _host_is_private(current_url))


class _PolicySession(requests.Session):
    """Requests session that validates each redirect before following it."""

    def get_redirect_target(self, resp: requests.Response) -> str | None:
        target = super().get_redirect_target(resp)
        if not target:
            return target
        current = str(getattr(resp, "url", "") or "")
        resolved = urllib.parse.urljoin(current, target)
        if not _redirect_allowed(current, resolved):
            raise requests.exceptions.InvalidURL(f"blocked out-of-scope redirect: {resolved}")
        return target


class _RequestsOpener:
    """Keep-alive transport with the same ``open(req, timeout=...)`` shape as urllib."""

    def __init__(self, session: requests.Session, timeout: int, follow_redirects: bool):
        self.session = session
        self.timeout = timeout
        self.follow_redirects = follow_redirects

    def open(self, req: urllib.request.Request, timeout: int | None = None) -> _RequestsResponse:
        headers = {str(key): str(value) for key, value in req.header_items()}
        response = self.session.request(
            method=req.get_method(),
            url=req.full_url,
            headers=headers,
            data=req.data,
            timeout=timeout if timeout is not None else self.timeout,
            allow_redirects=self.follow_redirects,
            stream=True,
        )
        return _RequestsResponse(response)


class HttpClient:
    """
    Unified HTTP client supporting cookie persistence, proxy routing,
    SSL bypass for lab environments, and custom headers.
    """

    def __init__(
        self,
        base_url: str | None = None,
        timeout: int = 12,
        proxy: str | None = None,
        user_agent: str = DEFAULT_USER_AGENT,
        verify_tls: bool | None = None,
    ):
        self.base_url = normalize_url(base_url) if base_url else None
        self._base_dir = f"{application_base_url(self.base_url)}/" if self.base_url else None
        self.timeout = timeout
        self.proxy = proxy
        self.user_agent = user_agent
        self.verify_tls = _TLS_VERIFY if verify_tls is None else verify_tls
        self.jar = RequestsCookieJar()
        self.transcript: list[dict[str, Any]] = []
        self.session = _PolicySession()
        self.session.cookies = self.jar
        self.session.trust_env = False
        self.session.verify = self.verify_tls
        self.session.proxies = {"http": proxy, "https": proxy} if proxy else {}
        self.session.headers["Accept-Encoding"] = "gzip, deflate"
        self._rebuild_opener()

    def _rebuild_opener(self) -> None:
        self.session.verify = self.verify_tls
        self.opener = _RequestsOpener(self.session, self.timeout, True)
        self.no_redirect_opener = _RequestsOpener(self.session, self.timeout, False)

    def close(self) -> None:
        self.session.close()

    def __enter__(self) -> Self:
        return self

    def __exit__(self, *args: object) -> None:
        self.close()

    def _resolve_url(self, url: str) -> str:
        if self.base_url and not url.startswith(("http://", "https://")):
            base = self._base_dir or f"{self.base_url.rstrip('/')}/"
            return urllib.parse.urljoin(base, url.lstrip("/"))
        return url

    def _record(self, method: str, url: str, response: dict[str, Any]) -> None:
        entry = _transcript_entry(method, url, response)
        self.transcript.append(entry)
        del self.transcript[: max(0, len(self.transcript) - _TRANSCRIPT_MAX)]
        _transcript_capture(method, url, response)

    def request(
        self,
        url: str,
        method: str = "GET",
        headers: dict[str, Any] | None = None,
        data: bytes | str | None = None,
        timeout: int | None = None,
        follow_redirects: bool = True,
    ) -> dict[str, Any]:
        full_url = self._resolve_url(url)
        req_headers: dict[str, Any] = {
            "User-Agent": self.user_agent,
            "Accept": DEFAULT_ACCEPT,
            "Accept-Language": DEFAULT_ACCEPT_LANGUAGE,
        }
        if headers:
            req_headers.update(headers)

        payload_bytes: bytes | None = None
        if data is not None:
            payload_bytes = data if isinstance(data, bytes) else data.encode("utf-8")

        effective_timeout = timeout if timeout is not None else self.timeout

        cache_key: tuple[str, int, str | None, bool, bool, str] | None = None
        with _discovery_cache_lock:
            cache_enabled = _discovery_cache_enabled
        if cache_enabled and method.upper() == "GET" and not headers and data is None and not self.jar:
            cache_key = (
                full_url,
                effective_timeout,
                self.proxy,
                self.verify_tls,
                follow_redirects,
                self.user_agent,
            )
            with _discovery_cache_lock:
                cached = _discovery_cache.get(cache_key)
            if cached is not None:
                return copy.deepcopy(cached)

        _acquire_rate_limit()
        try:
            req = urllib.request.Request(full_url, method=method, headers=req_headers, data=payload_bytes)
            opener = self.opener if follow_redirects else self.no_redirect_opener
            with opener.open(req, timeout=effective_timeout) as response:
                body_bytes = response.read(MAX_RESPONSE_BYTES + 1)
                truncated = len(body_bytes) > MAX_RESPONSE_BYTES
                body_bytes = body_bytes[:MAX_RESPONSE_BYTES]
                body_bytes, body, encoding_truncated = _decode_body(body_bytes, response.headers)
                truncated = truncated or encoding_truncated
                final_url: str = response.url or full_url
                if not follow_redirects and response.status in (301, 302, 303, 307, 308):
                    location = response.headers.get("Location") if hasattr(response.headers, "get") else None
                    if location:
                        final_url = urllib.parse.urljoin(full_url, str(location))
                result = _build_response_dict(
                    response.status, body, full_url, final_url, response.headers, body_bytes, truncated=truncated
                )
                self._record(method, full_url, result)
                if cache_key is not None and result.get("status", 0) > 0:
                    with _discovery_cache_lock:
                        _discovery_cache[cache_key] = result
                return result
        except urllib.error.HTTPError as exc:
            body_bytes = exc.read(MAX_RESPONSE_BYTES + 1) if hasattr(exc, "read") else b""
            truncated = len(body_bytes) > MAX_RESPONSE_BYTES
            body_bytes = body_bytes[:MAX_RESPONSE_BYTES]
            body_bytes, body, encoding_truncated = _decode_body(body_bytes, exc.headers or {})
            truncated = truncated or encoding_truncated
            final_url = exc.url if exc.url else full_url
            if exc.code in (301, 302, 303, 307, 308) and exc.headers is not None:
                location = exc.headers.get("Location")
                if location:
                    final_url = urllib.parse.urljoin(full_url, location)
            result = _build_response_dict(
                exc.code, body, full_url, final_url, exc.headers or {}, body_bytes, truncated=truncated
            )
            self._record(method, full_url, result)
            if cache_key is not None:
                with _discovery_cache_lock:
                    _discovery_cache[cache_key] = result
            return result
        except requests.TooManyRedirects as exc:
            last = getattr(exc, "response", None)
            last_url = str(getattr(last, "url", "") or full_url)
            result = _build_response_dict(
                0,
                "",
                full_url,
                last_url,
                {},
                error={
                    "type": "TooManyRedirects",
                    "message": f"redirect loop while following {full_url} (last hop: {last_url})",
                },
            )
            self._record(method, full_url, result)
            return result
        except Exception as exc:  # noqa: BLE001
            result = _build_response_dict(
                0,
                "",
                full_url,
                full_url,
                {},
                error={"type": type(exc).__name__, "message": str(exc)},
            )
            self._record(method, full_url, result)
            return result

    def get(self, url: str, headers: dict[str, Any] | None = None, timeout: int | None = None) -> dict[str, Any]:
        return self.request(url, method="GET", headers=headers, timeout=timeout)

    def post(
        self,
        url: str,
        data: bytes | str | dict[str, Any] | None = None,
        fields: dict[str, Any] | None = None,
        files: dict[str, Any] | None = None,
        headers: dict[str, Any] | None = None,
        timeout: int | None = None,
    ) -> dict[str, Any]:
        if files:
            return self.post_multipart(url, fields=fields or {}, files=files, headers=headers, timeout=timeout)
        post_headers: dict[str, Any] = dict(headers or {})
        post_data: bytes | str | None
        if fields:
            post_data = form_encode(fields)
            post_headers.setdefault("Content-Type", "application/x-www-form-urlencoded")
        elif isinstance(data, dict):
            post_data = form_encode(data)
            post_headers.setdefault("Content-Type", "application/x-www-form-urlencoded")
        else:
            post_data = data
        return self.request(url, method="POST", headers=post_headers, data=post_data, timeout=timeout)

    def post_multipart(
        self,
        url: str,
        fields: dict[str, Any],
        files: dict[str, Any],
        headers: dict[str, Any] | None = None,
        timeout: int | None = None,
    ) -> dict[str, Any]:
        content_type, body = build_multipart(fields, files)
        post_headers: dict[str, Any] = dict(headers or {})
        post_headers["Content-Type"] = content_type
        return self.request(url, method="POST", headers=post_headers, data=body, timeout=timeout)


# Backwards-compatible alias for session-style HTTP client
HttpSession = HttpClient


def request(
    url: str,
    method: str = "GET",
    headers: dict[str, Any] | None = None,
    data: bytes | str | None = None,
    timeout: int = 12,
    proxy: str | None = None,
) -> dict[str, Any]:
    """Convenience function for stateless HTTP requests matching legacy modules.

    The thread-local client is reused to avoid rebuilding the TLS context, but
    its cookie jar is cleared before every call: a session established by one
    detector or probe must never leak into the next module.
    """
    key = (timeout, proxy, _TLS_VERIFY)
    clients = getattr(_thread_clients, "clients", None)
    if clients is None:
        clients = {}
        _thread_clients.clients = clients
    client = clients.get(key)
    if client is None:
        client = HttpClient(timeout=timeout, proxy=proxy)
        clients[key] = client
    client.jar.clear()
    response = client.request(url, method=method, headers=headers, data=data, timeout=timeout)
    try:
        from .transcript import record_stateless

        record_stateless(method, url, response)
    except ImportError:  # pragma: no cover - transcript is part of core
        pass
    return response


def fetch_url(url: str, timeout: int = 12, proxy: str | None = None, session: Any = None) -> dict[str, Any]:
    """Convenience function for fetching a URL through the shared client."""
    if session is not None and hasattr(session, "get"):
        return cast(dict[str, Any], session.get(url, timeout=timeout))
    if not _discovery_cache_enabled:
        return request(url, method="GET", timeout=timeout, proxy=proxy)
    key = (url, timeout, proxy, _TLS_VERIFY, True, DEFAULT_USER_AGENT)
    with _discovery_cache_lock:
        cached = _discovery_cache.get(key)
    if cached is not None:
        return copy.deepcopy(cached)
    response = request(url, method="GET", timeout=timeout, proxy=proxy)
    if response.get("status", 0) > 0:
        with _discovery_cache_lock:
            _discovery_cache[key] = response
    return response


def probe_target_baseline(target: str, timeout: int = 8, proxy: str | None = None) -> dict[str, Any]:
    """Probes target baseline behavior using a random nonce canary path."""
    nonce = secrets.token_hex(6)
    scan_root = application_base_url(target)
    canary_path = f"/_jvh_probe_{nonce}/"
    canary_url = f"{scan_root}{canary_path}"
    root_response = fetch_url(f"{scan_root}/", timeout=timeout, proxy=proxy)
    resp = fetch_url(canary_url, timeout=timeout, proxy=proxy)
    target_root = scan_root
    final = resp.get("final_url", "").rstrip("/")
    redirected_to_root = final in (target_root, f"{target_root}/index.php")
    return {
        "status": resp.get("status", 0),
        "blanket_403": resp.get("status") == 403,
        "redirected_to_root": redirected_to_root,
        "body_hash": resp.get("body_hash", ""),
        "normalized_body_hash": resp.get("normalized_body_hash", ""),
        "body_len": resp.get("body_len", len(resp.get("body", ""))),
        "title": resp.get("title", ""),
        "target_root": target_root,
        "edge_interstitial": root_response.get("edge_interstitial"),
        "error": resp.get("error") or root_response.get("error"),
    }


def is_baseline_match(response: dict, baseline: dict | None, allow_403: bool = False) -> bool:
    """Determines whether a response matches the target's baseline non-existent path behavior."""
    if not baseline:
        return False
    if response.get("status", 0) <= 0:
        return False
    resp_hash = response.get("body_hash")
    base_hash = baseline.get("body_hash")
    if resp_hash and base_hash and resp_hash == base_hash:
        return True
    normalized_hash = response.get("normalized_body_hash")
    baseline_normalized_hash = baseline.get("normalized_body_hash")
    if normalized_hash and baseline_normalized_hash and normalized_hash == baseline_normalized_hash:
        return True
    # Similar title/length is useful diagnostic context, but is not sufficient
    # to reject a route when the normalized content hashes differ.
    if response.get("redirected") and baseline.get("target_root"):
        final_url = response.get("final_url", "").rstrip("/")
        root_url = baseline.get("target_root", "").rstrip("/")
        if final_url in (root_url, f"{root_url}/index.php"):
            return True
    return bool(response.get("status") == 403 and baseline.get("blanket_403") and not allow_403)


def poll_paths(
    fetch_fn: Any,
    paths: list[str],
    deadline: float = 3.5,
    initial_delay: float = 0.1,
    backoff: float = 1.4,
    max_delay: float = 0.8,
    accept_fn: Any = None,
) -> tuple[dict | None, str | None, int]:
    """
    Polls candidate paths with deadline and backoff to avoid false negatives
    on slow disks, network file systems, or Docker volume sync delays.

    Returns: (successful_response, successful_path, total_attempts)
    """
    import time
    start_time = time.monotonic()
    current_delay = initial_delay
    attempts = 0

    while time.monotonic() - start_time < deadline:
        for path in paths:
            if time.monotonic() - start_time >= deadline:
                return None, None, attempts
            attempts += 1
            resp = fetch_fn(path)
            if resp and resp.get("status") == 200 and (accept_fn is None or accept_fn(resp)):
                return resp, path, attempts
        remaining = deadline - (time.monotonic() - start_time)
        if remaining <= 0:
            break
        time.sleep(min(current_delay, remaining))
        current_delay = min(current_delay * backoff, max_delay)

    return None, None, attempts
