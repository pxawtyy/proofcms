"""Generate the local archive inventory and checksums.

The archive tree lives outside Git. This tool scans it, counts how often the
repository references each top-level item, and writes:

    <root>/INDEX.md
    <root>/../checksums/SHA256SUMS.txt

Run it after adding or removing a fixture package. It never modifies the
archives themselves.
"""

from __future__ import annotations

import argparse
import hashlib
from datetime import datetime, timezone
from pathlib import Path

DEFAULT_ROOT = Path("D:/ProofCMS-Labs/archives")
DEFAULT_REPO = Path(__file__).resolve().parent.parent
ARCHIVE_SUFFIXES = {".zip", ".exe", ".7z", ".tar", ".gz", ".tgz"}
REPO_SUFFIXES = {".md", ".ps1", ".py", ".yml", ".yaml", ".json", ".php"}


def _dir_size(path: Path) -> int:
    return sum(item.stat().st_size for item in path.rglob("*") if item.is_file())


def _sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _repo_texts(repo: Path) -> list[str]:
    texts: list[str] = []
    for path in repo.rglob("*"):
        if not path.is_file() or path.suffix.lower() not in REPO_SUFFIXES:
            continue
        if ".git" in path.parts:
            continue
        try:
            texts.append(path.read_text(encoding="utf-8", errors="ignore"))
        except OSError:
            continue
    return texts


def _human_size(size: int) -> str:
    if size >= 1024 * 1024 * 1024:
        return f"{size / (1024 ** 3):.2f} GB"
    if size >= 1024 * 1024:
        return f"{size / (1024 ** 2):.1f} MB"
    if size >= 1024:
        return f"{size / 1024:.1f} KB"
    return f"{size} B"


def _index_row(name: str, kind: str, size: int, refs: int) -> str:
    return f"| `{name}` | {kind} | {_human_size(size)} | {refs} |"


def build(root: Path, repo: Path) -> tuple[str, str]:
    if not root.is_dir():
        raise SystemExit(f"archive root not found: {root}")
    texts = _repo_texts(repo)
    lines = [
        "# Archive index",
        "",
        f"Generated by `tools/archive_index.py` on {datetime.now(timezone.utc).date().isoformat()}.",
        "",
        f"Root: `{root}`",
        "",
        "A zero reference count means the repository does not mention the item by",
        "name; a lab may still mount a parent directory or use a renamed copy.",
        "",
    ]
    checksums: list[str] = []

    for group in sorted(path for path in root.iterdir() if path.is_dir()):
        lines.extend([f"## {group.name}", "", "| Item | Type | Size | Refs |", "|---|---|---:|---:|"])
        for item in sorted(group.iterdir()):
            kind = "tree" if item.is_dir() else "file"
            size = _dir_size(item) if item.is_dir() else item.stat().st_size
            refs = sum(1 for text in texts if item.name in text)
            lines.append(_index_row(item.name, kind, size, refs))
            if item.is_file() and item.suffix.lower() in ARCHIVE_SUFFIXES:
                checksums.append(f"{_sha256(item)}  {group.name}/{item.name}")
        lines.append("")

    return "\n".join(lines) + "\n", "\n".join(sorted(checksums)) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=DEFAULT_ROOT, help="archive tree root")
    parser.add_argument("--repo", type=Path, default=DEFAULT_REPO, help="repository root for reference counts")
    parser.add_argument(
        "--checksums",
        type=Path,
        default=None,
        help="checksum file path (default: <root>/../checksums/SHA256SUMS.txt)",
    )
    args = parser.parse_args()

    index, checksum_text = build(args.root, args.repo)
    index_path = args.root / "INDEX.md"
    checksum_path = args.checksums or (args.root.parent / "checksums" / "SHA256SUMS.txt")
    index_path.write_text(index, encoding="utf-8")
    checksum_path.parent.mkdir(parents=True, exist_ok=True)
    checksum_path.write_text(checksum_text, encoding="utf-8")
    print(f"wrote {index_path}")
    print(f"wrote {checksum_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
